//! Generate kotlinc's diagnostic names (`src/diag/names.rs` includes the result).

use std::path::{Path, PathBuf};

// Rerunning a script does not recompile it. Include checkout identity in this script's dep-info.
const _: Option<&str> = option_env!("KRUSTY_BUILD_CHECKOUT");

fn main() {
    println!("cargo:rerun-if-env-changed=KRUSTY_BUILD_CHECKOUT");
    if let Err(error) = generate_diagnostic_names() {
        eprintln!("{error}");
        std::process::exit(1);
    }
}

/// One constant per kotlinc diagnostic name any vendored release declares, in sorted order, and
/// their spellings (`src/diag/names.rs` includes the result). Each release's own table still decides
/// whether that release declares a name.
fn generate_diagnostic_names() -> Result<(), String> {
    let releases = Path::new("src/diag/releases");
    println!("cargo:rerun-if-changed={}", releases.display());
    let mut names = std::collections::BTreeSet::new();
    let entries = std::fs::read_dir(releases)
        .map_err(|error| format!("read {}: {error}", releases.display()))?;
    for entry in entries {
        let path = entry
            .map_err(|error| format!("read {}: {error}", releases.display()))?
            .path();
        if !path.to_string_lossy().ends_with(".diagnostics.tsv") {
            continue;
        }
        let table = std::fs::read_to_string(&path)
            .map_err(|error| format!("read {}: {error}", path.display()))?;
        for row in table.lines().filter(|line| !line.starts_with('#')) {
            let name = row.split('\t').next().unwrap_or_default();
            if name.is_empty()
                || !name
                    .bytes()
                    .all(|byte| byte.is_ascii_uppercase() || byte.is_ascii_digit() || byte == b'_')
            {
                return Err(format!(
                    "{}: invalid diagnostic name {name:?}",
                    path.display()
                ));
            }
            names.insert(name.to_string());
        }
    }
    let mut generated =
        String::from("// Generated by build.rs from src/diag/releases/*.diagnostics.tsv.\n");
    for (index, name) in names.iter().enumerate() {
        generated.push_str(&format!(
            "pub const {name}: DiagnosticName = DiagnosticName({index});\n"
        ));
    }
    generated.push_str(&format!("static SPELLINGS: [&str; {}] = [\n", names.len()));
    for name in &names {
        generated.push_str(&format!("    \"{name}\",\n"));
    }
    generated.push_str("];\n");
    let out_dir = PathBuf::from(std::env::var("OUT_DIR").expect("OUT_DIR"));
    std::fs::write(out_dir.join("diagnostic_names.rs"), generated)
        .map_err(|error| format!("write diagnostic names: {error}"))
}
