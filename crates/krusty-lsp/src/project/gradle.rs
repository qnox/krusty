    #[test]
    fn the_probe_injects_an_init_script_and_never_edits_the_project() {
        let tree = TempTree::new("gradle-command");
        tree.write("settings.gradle.kts", "");
        tree.write("gradlew", "#!/bin/sh\n");
        let provider = GradleProvider::new(tree.root());
        let runner = FakeRunner::new(vec![FakeRunner::stdout(&recorded_output())]);

        provider.probe(&runner).unwrap();

        let command = runner.command(0);
        assert_eq!(command.program, tree.path("gradlew"));
        assert_eq!(command.working_directory, tree.root);
        assert_eq!(command.args[0], "--quiet");
        assert_eq!(command.args[1], "--console=plain");
        assert_eq!(command.args[2], "--no-configuration-cache");
        assert_eq!(command.args[3], "--init-script");
        assert_eq!(command.args[5], TASK);

        let script = std::fs::read_to_string(&command.args[4]).unwrap();
        assert!(script.contains("lenient = true"), "{script}");
        assert!(script.contains("compileTask?.compilerOptions"), "{script}");
        assert!(script.contains("set.allJava?.srcDirs"), "{script}");
        assert!(
            script.contains("set.extensions.findByName(\"kotlin\")?.srcDirs"),
            "{script}"
        );
        assert!(
            script.contains("compilation.defaultSourceSet?.name"),
            "{script}"
        );
        assert!(!script.contains("set.allSource?.srcDirs"), "{script}");
        assert!(!tree.path(".krusty").exists());
    }

