    #[test]
    fn an_android_project_becomes_one_module_per_variant_with_the_platform_jar() {
        let app = concat!(
            r#"{"path":":app","name":"app","projectDir":"/p/app","javaHome":"/jdk17","jvmTarget":"1.8","kotlincArgs":["-XXLanguage:+ProjectFeature"],"sourceSets":[],"kotlinCompilations":[],"androidVariants":["#,
            r#"{"name":"debug","roots":["/p/app/src/main/kotlin","/p/app/src/debug/kotlin"],"classpath":["/sdk/platforms/android-34/android.jar","/p/app/build/generated/R.jar","/m2/appcompat.jar"],"output":["/p/app/build/tmp/kotlin-classes/debug"],"isTest":false,"kotlincArgs":["-XXLanguage:+DebugFeature"]},"#,
            r#"{"name":"release","roots":["/p/app/src/main/kotlin"],"classpath":["/sdk/platforms/android-34/android.jar"],"output":["/p/app/build/tmp/kotlin-classes/release"],"isTest":false}"#,
            r#"],"projectDeps":[]}"#,
        );
        let output = format!("{SENTINEL}{app}\n");
        let model = parse_model(Path::new("/p"), &output).unwrap();

        assert!(model.module(&ModuleId::new(":app", "main")).is_none());
        let debug = model.module(&ModuleId::new(":app", "debug")).unwrap();
        assert_eq!(debug.source_roots.len(), 2);
        assert!(debug
            .classpath
            .contains(&PathBuf::from("/sdk/platforms/android-34/android.jar")));
        assert!(debug
            .classpath
            .contains(&PathBuf::from("/p/app/build/generated/R.jar")));
        assert_eq!(debug.jvm_target.as_deref(), Some("1.8"));
        assert_eq!(
            debug.kotlinc_args,
            vec![
                "-XXLanguage:+ProjectFeature".to_string(),
                "-XXLanguage:+DebugFeature".to_string(),
            ]
        );
        let release = model.module(&ModuleId::new(":app", "release")).unwrap();
        assert_eq!(
            release.kotlinc_args,
            vec!["-XXLanguage:+ProjectFeature".to_string()]
        );
    }

    #[test]
    fn android_takes_precedence_over_plain_source_sets_in_a_kotlin_android_project() {
        // A kotlin-android project reports BOTH a source-set container and variants; the variants win.
        let app = concat!(
            r#"{"path":":app","name":"app","projectDir":"/p/app","javaHome":"/jdk17","jvmTarget":null,"kotlincArgs":[],"#,
            r#""sourceSets":[{"name":"main","roots":["/p/app/src/main/java"],"classpath":[],"output":[]}],"#,
            r#""kotlinCompilations":[],"#,
            r#""androidVariants":[{"name":"debug","roots":["/p/app/src/main/kotlin"],"classpath":["/sdk/android.jar"],"output":[],"isTest":false}],"#,
            r#""projectDeps":[]}"#,
        );
        let output = format!("{SENTINEL}{app}\n");
        let model = parse_model(Path::new("/p"), &output).unwrap();
        assert!(model.module(&ModuleId::new(":app", "debug")).is_some());
        assert!(model.module(&ModuleId::new(":app", "main")).is_none());
    }

