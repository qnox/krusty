#[derive(Debug)]
pub struct GradleProvider {
    root: PathBuf,
    gradle: PathBuf,
    init_script: PathBuf,
}

impl GradleProvider {
    pub fn new(root: impl Into<PathBuf>) -> Self {
        let root = root.into();
        let gradle = GRADLE.resolve(&root);
        let init_script = init_script_path(&root);
        Self {
            root,
            gradle,
            init_script,
        }
    }

    pub fn build_files(&self) -> Vec<PathBuf> {
        collect_build_files(&self.root, 8, &is_gradle_build_file)
    }

    pub fn command(&self) -> Command {
        Command::new(self.gradle.clone(), self.root.clone()).args([
            "--quiet".to_string(),
            "--console=plain".to_string(),
            // Gradle's configuration cache rejects the probe's execution-time project access.
            "--no-configuration-cache".to_string(),
            "--init-script".to_string(),
            self.init_script.to_string_lossy().into_owned(),
            TASK.to_string(),
        ])
    }

    fn write_init_script(&self) -> Result<(), ProbeError> {
        if let Some(parent) = self.init_script.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|error| ProbeError::Io(format!("{}: {error}", parent.display())))?;
        }
        std::fs::write(&self.init_script, INIT_SCRIPT)
            .map_err(|error| ProbeError::Io(format!("{}: {error}", self.init_script.display())))
    }
}

impl ProjectProvider for GradleProvider {
    fn kind(&self) -> ProviderKind {
        ProviderKind::Gradle
    }

    fn root(&self) -> &Path {
        &self.root
    }

    fn watch_paths(&self) -> Vec<PathBuf> {
        self.build_files()
    }

    fn fingerprint_salt(&self) -> String {
        format!("gradle-{PROBE_VERSION}")
    }

    fn probe(&self, runner: &dyn CommandRunner) -> Result<ProjectModel, ProbeError> {
        self.write_init_script()?;
        let command = self.command();
        let output = runner
            .run(&command)
            .map_err(|error| ProbeError::Io(format!("{}: {error}", self.gradle.display())))?;
        if !output.succeeded() {
            return Err(ProbeError::Tool {
                program: self.gradle.to_string_lossy().into_owned(),
                status: output.status,
                message: gradle_failure_summary(&output.stderr, &output.stdout),
            });
        }
        parse_model(&self.root, &output.stdout)
    }
}

fn init_script_path(root: &Path) -> PathBuf {
    let mut hasher = super::fingerprint::Hasher::default();
    hasher.write_str(&root.to_string_lossy());
    std::env::temp_dir().join(format!(
        "krusty-gradle-{:016x}-v{PROBE_VERSION}.init.gradle",
        hasher.finish().as_u64()
    ))
}

fn is_gradle_build_file(path: &Path) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };
    name.ends_with(".gradle")
        || name.ends_with(".gradle.kts")
        || name == "gradle.properties"
        || name == "libs.versions.toml"
        || name == "gradle-wrapper.properties"
        || name == "gradle.lockfile"
}

fn parse_model(root: &Path, stdout: &str) -> Result<ProjectModel, ProbeError> {
    let mut projects = Vec::new();
    for line in stdout.lines() {
        let Some(payload) = line.trim_start().strip_prefix(SENTINEL) else {
            continue;
        };
        let project: GradleProject = serde_json::from_str(payload)
            .map_err(|error| ProbeError::Parse(format!("{error} in `{payload}`")))?;
        projects.push(project);
    }
    if projects.is_empty() {
        return Err(ProbeError::Parse(
            "no project model lines in gradle output".to_string(),
        ));
    }

    let jdk_home = projects
        .iter()
        .find_map(|project| project.java_home.clone())
        .map(PathBuf::from);
    let mut modules = Vec::new();
    for project in &projects {
        // Android and multiplatform replace the plain source-set view: an Android project's JVM
        // sources are organised per variant, and a multiplatform project has no SourceSetContainer
        // at all. Prefer the richer view when the corresponding plugin reported one.
        if !project.android_variants.is_empty() {
            for variant in &project.android_variants {
                modules.push(android_module_of(project, variant));
            }
        } else if !project.kotlin_compilations.is_empty() {
            for compilation in project
                .kotlin_compilations
                .iter()
                .filter(|compilation| compilation.platform == "jvm")
            {
                modules.push(kmp_module_of(project, compilation));
            }
        } else {
            for source_set in &project.source_sets {
                modules.push(module_of(project, source_set));
            }
        }
    }
    Ok(ProjectModel {
        root: root.to_path_buf(),
        kind: ProviderKind::Gradle,
        jdk_home,
        modules,
    })
}

fn module_of(project: &GradleProject, source_set: &GradleSourceSet) -> Module {
    let kind = if is_test_source_set(&source_set.name) {
        SourceRootKind::Test
    } else {
        SourceRootKind::Source
    };
    let mut module = Module::new(
        ModuleId::new(&project.path, &source_set.name),
        &project.project_dir,
    );
    module.display_name = format!("{}:{}", project.name, source_set.name);
    module.source_roots = source_set
        .roots
        .iter()
        .map(|root| SourceRoot {
            path: PathBuf::from(root),
            kind,
            generated: false,
            package_prefix: String::new(),
        })
        .collect();
    module.classpath = source_set.classpath.iter().map(PathBuf::from).collect();
    module.outputs = source_set
        .output
        .iter()
        .map(ModuleOutput::classes)
        .collect();
    module.jvm_target = project.jvm_target.clone();
    module.kotlinc_args = merged_kotlinc_args(&project.kotlinc_args, &source_set.kotlinc_args);
    module.depends_on = project
        .project_deps
        .iter()
        .map(|path| ModuleId::new(path, "main"))
        .collect();

    // A test source set sees its own project's `main` output, including `internal` declarations:
    // that is Gradle's association, and the compiler needs it as a friend path.
    if kind == SourceRootKind::Test {
        let main = ModuleId::new(&project.path, "main");
        if !module.depends_on.contains(&main) {
            module.depends_on.push(main);
        }
        for output in project
            .source_sets
            .iter()
            .filter(|set| set.name == "main")
            .flat_map(|set| set.output.iter())
        {
            module.friend_paths.push(PathBuf::from(output));
        }
    }
    module
}

/// One Kotlin Multiplatform compilation becomes a module keyed `<target>/<compilation>`
/// (e.g. `jvm/main`), so `jvm/main` and `jvm/test` stay distinct compilation units.
fn kmp_module_of(project: &GradleProject, compilation: &KotlinCompilation) -> Module {
    let source_set = format!("{}/{}", compilation.target, compilation.name);
    let kind = if compilation.is_test {
        SourceRootKind::Test
    } else {
        SourceRootKind::Source
    };
    let mut module = Module::new(
        ModuleId::new(&project.path, &source_set),
        &project.project_dir,
    );
    module.display_name = format!("{}:{source_set}", project.name);
    module.source_roots = compilation
        .roots
        .iter()
        .map(|root| SourceRoot {
            path: PathBuf::from(root),
            kind,
            generated: false,
            package_prefix: String::new(),
        })
        .collect();
    module.classpath = compilation.classpath.iter().map(PathBuf::from).collect();
    module.outputs = compilation
        .output
        .iter()
        .map(ModuleOutput::classes)
        .collect();
    module.friend_paths = compilation.associates.iter().map(PathBuf::from).collect();
    module.jvm_target = compilation
        .jvm_target
        .clone()
        .or_else(|| project.jvm_target.clone());
    module.kotlinc_args = merged_kotlinc_args(&project.kotlinc_args, &compilation.kotlinc_args);
    module.depends_on = project
        .project_deps
        .iter()
        .map(|path| ModuleId::new(path, "main"))
        .collect();
    module
}

/// One Android variant becomes a module keyed by the variant name (`debug`, `release`). The AGP
/// compile classpath already includes the platform `android.jar` and the generated `R.jar`.
fn android_module_of(project: &GradleProject, variant: &AndroidVariant) -> Module {
    let kind = if variant.is_test {
        SourceRootKind::Test
    } else {
        SourceRootKind::Source
    };
    let mut module = Module::new(
        ModuleId::new(&project.path, &variant.name),
        &project.project_dir,
    );
    module.display_name = format!("{}:{}", project.name, variant.name);
    module.source_roots = variant
        .roots
        .iter()
        .map(|root| SourceRoot {
            path: PathBuf::from(root),
            kind,
            generated: false,
            package_prefix: String::new(),
        })
        .collect();
    module.classpath = variant.classpath.iter().map(PathBuf::from).collect();
    module.outputs = variant.output.iter().map(ModuleOutput::classes).collect();
    module.jvm_target = project.jvm_target.clone();
    module.kotlinc_args = merged_kotlinc_args(&project.kotlinc_args, &variant.kotlinc_args);
    module.depends_on = project
        .project_deps
        .iter()
        .map(|path| ModuleId::new(path, "main"))
        .collect();
    module
}

fn merged_kotlinc_args(project: &[String], compilation: &[String]) -> Vec<String> {
    let mut merged = Vec::new();
    for argument in project.iter().chain(compilation) {
        if !merged.contains(argument) {
            merged.push(argument.clone());
        }
    }
    merged
}

fn is_test_source_set(name: &str) -> bool {
    name == "test" || name.ends_with("Test") || name.ends_with("test")
}

fn gradle_failure_summary(stderr: &str, stdout: &str) -> String {
    gradle_failure_details(stderr)
        .or_else(|| gradle_failure_details(stdout))
        .unwrap_or_else(|| {
            stderr
                .lines()
                .chain(stdout.lines())
                .map(str::trim)
                .find(|line| !line.is_empty())
                .unwrap_or_default()
                .to_string()
        })
}

fn gradle_failure_details(output: &str) -> Option<String> {
    let mut lines = output.lines().map(str::trim_end);
    while let Some(line) = lines.next() {
        if line.trim() != "* What went wrong:" {
            continue;
        }
        let mut cause = Vec::new();
        let mut truncated = false;
        for detail in lines.by_ref() {
            let detail = detail.trim();
            if detail.is_empty() || detail.starts_with('*') {
                break;
            }
            let detail = detail.trim_start_matches('>').trim();
            if detail.is_empty() {
                continue;
            }
            if cause.len() == MAX_FAILURE_DETAILS {
                truncated = true;
                break;
            }
            cause.push(detail);
        }
        if !cause.is_empty() {
            let mut summary = cause.join(" — ");
            if truncated {
                summary.push_str(" — ...");
            }
            return Some(summary);
        }
    }
    None
}

