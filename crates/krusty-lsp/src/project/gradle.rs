/// Printed by the init script, one line per Gradle project.
///
/// `artifactView { lenient = true }` is what keeps a single unresolvable dependency from failing the
/// whole sync — without it one typo in one module leaves the editor with no classpath at all.
const INIT_SCRIPT: &str = r#"// Generated by krusty-lsp. Injected with -I; the project is not modified.
allprojects { project ->
    project.tasks.register("krustyModel") {
        doLast {
            def lenient = { configuration ->
                configuration == null ? [] :
                    configuration.incoming.artifactView { view -> view.lenient = true }
                        .files.collect { it.absolutePath }
            }

            // Plain Kotlin/JVM and Java: the SourceSetContainer. Absent for multiplatform.
            def sourceSets = []
            project.extensions.findByName("sourceSets")?.each { set ->
                def roots = [] as Set
                set.allJava?.srcDirs?.each { roots << it.absolutePath }
                try {
                    set.extensions.findByName("kotlin")?.srcDirs?.each { roots << it.absolutePath }
                } catch (ignored) {
                }
                def compilerArgs = []
                try {
                    def compileTask = project.tasks.findByName(set.getCompileTaskName("kotlin"))
                    compilerArgs = compileTask?.compilerOptions?.freeCompilerArgs?.getOrElse([]) ?: []
                } catch (ignored) {
                }
                sourceSets << [
                    name      : set.name,
                    roots     : roots.toList().sort(),
                    classpath : lenient(project.configurations.findByName(set.compileClasspathConfigurationName)),
                    output    : set.output?.classesDirs?.files?.collect { it.absolutePath } ?: [],
                    kotlincArgs: compilerArgs.collect { it.toString() },
                ]
            }

            // Kotlin Multiplatform: one entry per compilation (jvm/main, jvm/test, …). The natural
            // compilation unit carries both the union of its source sets' directories and the compile
            // classpath, which lives on the compilation rather than on any single source set.
            def kotlinCompilations = []
            try {
                def kotlin = project.extensions.findByName("kotlin")
                if (kotlin != null && project.plugins.hasPlugin("org.jetbrains.kotlin.multiplatform")) {
                    kotlin.targets.findAll { target -> target.platformType?.name == "jvm" }.each { target ->
                        target.compilations.each { compilation ->
                            def roots = [] as Set
                            compilation.allKotlinSourceSets.each { ss ->
                                ss.kotlin?.srcDirs?.each { roots << it.absolutePath }
                            }
                            try {
                                def javaSourceSet = project.extensions.findByName("sourceSets")
                                    ?.findByName(compilation.defaultSourceSet?.name)
                                javaSourceSet?.allJava?.srcDirs?.each { roots << it.absolutePath }
                            } catch (ignored) {
                            }
                            def associates = []
                            try { associates = compilation.associateWith.collect { it.output?.classesDirs?.files }.flatten().findAll { it != null }.collect { it.absolutePath } } catch (ignored) {}
                            def compilerArgs = []
                            try { compilerArgs = compilation.compileTaskProvider.get().compilerOptions?.freeCompilerArgs?.getOrElse([]) ?: [] } catch (ignored) {}
                            kotlinCompilations << [
                                target    : target.name,
                                name      : compilation.name,
                                platform  : target.platformType?.name,
                                roots     : roots.toList().sort(),
                                classpath : compilation.compileDependencyFiles?.collect { it.absolutePath } ?: [],
                                output    : compilation.output?.classesDirs?.files?.collect { it.absolutePath } ?: [],
                                isTest    : compilation.name.toLowerCase().contains("test"),
                                associates: associates,
                                jvmTarget : (target.platformType?.name == "jvm") ? (compilation.compilerOptions?.options?.jvmTarget?.getOrNull()?.target) : null,
                                kotlincArgs: compilerArgs.collect { it.toString() },
                            ]
                        }
                    }
                }
            } catch (ignored) {
            }

            // Android: one entry per variant, with the AGP compile classpath and the platform jar.
            def androidVariants = []
            try {
                def android = project.extensions.findByName("android")
                if (android != null) {
                    def boot = []
                    try { boot = android.bootClasspath.collect { it.absolutePath } } catch (ignored) {}
                    def variants = android.hasProperty("applicationVariants") ? android.applicationVariants :
                                   (android.hasProperty("libraryVariants") ? android.libraryVariants : [])
                    variants.each { variant ->
                        def roots = [] as Set
                        variant.sourceSets.each { ss ->
                            ss.javaDirectories?.each { roots << it.absolutePath }
                            try { ss.kotlinDirectories?.each { roots << it.absolutePath } } catch (ignored) {}
                        }
                        def classpath = boot as List
                        try { classpath = classpath + variant.getCompileClasspath(null).files.collect { it.absolutePath } } catch (ignored) {}
                        def output = []
                        try { output = variant.javaCompileProvider.get().destinationDirectory.get().asFile.absolutePath } catch (ignored) {}
                        def compilerArgs = []
                        try {
                            def taskName = "compile${variant.name.capitalize()}Kotlin"
                            def compileTask = project.tasks.findByName(taskName)
                            compilerArgs = compileTask?.compilerOptions?.freeCompilerArgs?.getOrElse([]) ?: []
                        } catch (ignored) {}
                        androidVariants << [
                            name      : variant.name,
                            roots     : roots.toList().sort(),
                            classpath : classpath.unique(),
                            output    : output ? [output] : [],
                            isTest    : variant.name.toLowerCase().contains("test"),
                            kotlincArgs: compilerArgs.collect { it.toString() },
                        ]
                    }
                }
            } catch (ignored) {
            }

            def kotlin = project.extensions.findByName("kotlin")
            def jvmTarget = null
            def kotlincArgs = []
            try {
                jvmTarget = kotlin?.compilerOptions?.jvmTarget?.getOrNull()?.target
                kotlincArgs.addAll(kotlin?.compilerOptions?.freeCompilerArgs?.getOrElse([]) ?: [])
            } catch (ignored) {
            }
            kotlincArgs = kotlincArgs.collect { it.toString() }.unique()
            def javaHome = null
            try {
                def java = project.extensions.findByType(org.gradle.api.plugins.JavaPluginExtension)
                javaHome = java?.toolchain?.installationPath?.getOrNull()?.asFile?.absolutePath
            } catch (ignored) {
            }
            def model = [
                path              : project.path,
                name              : project.name,
                projectDir        : project.projectDir.absolutePath,
                javaHome          : javaHome ?: System.getProperty("java.home"),
                jvmTarget         : jvmTarget,
                kotlincArgs       : kotlincArgs,
                sourceSets        : sourceSets,
                kotlinCompilations: kotlinCompilations,
                androidVariants   : androidVariants,
                projectDeps       : project.configurations.findAll { it.name == "implementation" || it.name == "api" }
                    .collectMany { configuration ->
                        configuration.dependencies
                            .findAll { it instanceof org.gradle.api.artifacts.ProjectDependency }
                            .collect { it.path ?: it.dependencyProject.path }
                    }.unique(),
            ]
            println "KRUSTY_MODEL_JSON " + groovy.json.JsonOutput.toJson(model)
        }
    }
}
"#;

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct GradleProject {
    path: String,
    name: String,
    project_dir: String,
    #[serde(default)]
    java_home: Option<String>,
    #[serde(default)]
    jvm_target: Option<String>,
    #[serde(default)]
    kotlinc_args: Vec<String>,
    #[serde(default)]
    source_sets: Vec<GradleSourceSet>,
    #[serde(default)]
    kotlin_compilations: Vec<KotlinCompilation>,
    #[serde(default)]
    android_variants: Vec<AndroidVariant>,
    #[serde(default)]
    project_deps: Vec<String>,
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
