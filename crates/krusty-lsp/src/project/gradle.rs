#[derive(Debug)]
pub struct GradleProvider {
    root: PathBuf,
    init_script: PathBuf,
    probe_timeout: Duration,
    /// Scan and offline model only. The editor probe leaves dependency jars where they are.
    materialize_dependencies: bool,
    /// Replaces filesystem JDK discovery. Production probes leave this empty.
    #[cfg(test)]
    jvm_search: Option<super::gradle_daemon_jvm::JvmSearch>,
    /// Gradle user home consulted for isolated projects. Tests leave this empty so a machine
    /// `gradle.properties` cannot change the probe arguments.
    #[cfg(test)]
    gradle_user_home: Option<PathBuf>,
}

impl GradleProvider {
    /// Editor probe. The build action keeps the ordinary 120-second ceiling and does not download.
    pub fn new(root: impl Into<PathBuf>) -> Self {
        Self::with_probe_timeout(root, BUILD_TOOL_TIMEOUT, false)
    }

    /// Offline model and parity probe. The build action may run for [`PROBE_TIMEOUT`], and it asks
    /// Gradle to download external artifacts and build the project jars on each compile classpath.
    pub fn for_scan(root: impl Into<PathBuf>) -> Self {
        Self::with_probe_timeout(root, PROBE_TIMEOUT, true)
    }

    fn with_probe_timeout(
        root: impl Into<PathBuf>,
        probe_timeout: Duration,
        materialize_dependencies: bool,
    ) -> Self {
        let root = root.into();
        let init_script = init_script_path(&root);
        Self {
            root,
            init_script,
            probe_timeout,
            materialize_dependencies,
            #[cfg(test)]
            jvm_search: None,
            #[cfg(test)]
            gradle_user_home: None,
        }
    }

    #[cfg(test)]
    fn with_jvm_search(mut self, search: super::gradle_daemon_jvm::JvmSearch) -> Self {
        self.jvm_search = Some(search);
        self
    }

    #[cfg(test)]
    fn with_gradle_user_home(mut self, home: PathBuf) -> Self {
        self.gradle_user_home = Some(home);
        self
    }

    pub fn build_files(&self) -> Vec<PathBuf> {
        collect_build_files(&self.root, 8, &is_gradle_build_file)
    }

    fn build_action(&self) -> GradleBuildAction {
        let mut arguments = vec!["--quiet".to_string(), "--console=plain".to_string()];
        // The configuration cache rejects the probe's execution-time project access. Isolated
        // projects require that cache, and Gradle refuses this flag while they are enabled.
        if !self.isolated_projects_enabled() {
            arguments.push("--no-configuration-cache".to_string());
        }
        // `--continue` leaves the modules whose artifacts did land on disk.
        if self.materialize_dependencies {
            arguments.push("--continue".to_string());
        }
        arguments.push("--init-script".to_string());
        arguments.push(self.init_script.to_string_lossy().into_owned());
        let mut tasks = Vec::new();
        if self.materialize_dependencies {
            tasks.push(DOWNLOAD_TASK.to_string());
        }
        tasks.push(TASK.to_string());
        GradleBuildAction {
            project_dir: self.root.clone(),
            distribution: Distribution::BuildDistribution,
            tasks,
            arguments,
            timeout: self.probe_timeout,
            java_home: self.daemon_java_home(),
        }
    }

    fn isolated_projects_enabled(&self) -> bool {
        let version = gradle_wrapper_release(&self.root);
        let user = self.probe_gradle_user_home();
        let mut enabled = None;
        // Gradle 7.1 introduced the unsafe name. A wrapper we cannot read keeps that name, which
        // is the property the existing probes set.
        if version.is_none_or(|release| release >= GRADLE_UNSAFE_ISOLATED_PROJECTS) {
            record_isolated_projects(
                &mut enabled,
                effective_property(user.as_deref(), &self.root, UNSAFE_ISOLATED_PROJECTS),
            );
        }
        // Gradle 9.7 adds `org.gradle.isolated-projects`. An explicit false from either name
        // disables the feature.
        if version.is_some_and(|release| release >= GRADLE_CANONICAL_ISOLATED_PROJECTS) {
            record_isolated_projects(
                &mut enabled,
                effective_property(user.as_deref(), &self.root, CANONICAL_ISOLATED_PROJECTS),
            );
        }
        enabled == Some(true)
    }

    #[cfg(test)]
    fn probe_gradle_user_home(&self) -> Option<PathBuf> {
        self.gradle_user_home.clone()
    }

    #[cfg(not(test))]
    fn probe_gradle_user_home(&self) -> Option<PathBuf> {
        Some(super::tooling::gradle_user_home())
    }

    fn daemon_java_home(&self) -> Option<PathBuf> {
        #[cfg(test)]
        if let Some(search) = &self.jvm_search {
            return super::gradle_daemon_jvm::daemon_java_home(&self.root, search);
        }
        super::gradle_daemon_jvm::daemon_java_home(
            &self.root,
            &super::gradle_daemon_jvm::JvmSearch::system(&self.root),
        )
    }

    fn write_init_script(&self) -> Result<(), ProbeError> {
        if let Some(parent) = self.init_script.parent() {
            std::fs::create_dir_all(parent)
                .map_err(|error| ProbeError::Io(format!("{}: {error}", parent.display())))?;
        }
        std::fs::write(
            &self.init_script,
            init_script(self.materialize_dependencies),
        )
        .map_err(|error| ProbeError::Io(format!("{}: {error}", self.init_script.display())))
    }
}

impl ProjectProvider for GradleProvider {
    fn kind(&self) -> ProviderKind {
        ProviderKind::Gradle
    }

    fn root(&self) -> &Path {
        &self.root
    }

    fn watch_paths(&self) -> Vec<PathBuf> {
        self.build_files()
    }

    fn fingerprint_salt(&self) -> String {
        format!("gradle-{PROBE_VERSION}")
    }

    fn probe(&self, _runner: &dyn CommandRunner) -> Result<ProjectModel, ProbeError> {
        self.write_init_script()?;
        let action = self.build_action();
        let output = tooling::run_gradle(&action)
            .map_err(|error| ProbeError::Io(format!("{TOOLING_ENTRY}: {error}")))?;
        // A dependency task can fail while the model task still printed every project. The scan
        // keeps that model; an entry Gradle did not produce stays missing. The editor probe has
        // no download task, so any failure is the model itself.
        let model_was_printed = output.stdout.contains(SENTINEL);
        if !output.succeeded() && !(self.materialize_dependencies && model_was_printed) {
            return Err(ProbeError::Tool {
                program: TOOLING_ENTRY.to_string(),
                status: output.status,
                message: gradle_failure_summary(&output.stderr, &output.stdout),
            });
        }
        parse_model(&self.root, &output.stdout)
    }
}

fn init_script_path(root: &Path) -> PathBuf {
    let mut hasher = super::fingerprint::Hasher::default();
    hasher.write_str(&root.to_string_lossy());
    std::env::temp_dir().join(format!(
        "krusty-gradle-{:016x}-v{PROBE_VERSION}.init.gradle",
        hasher.finish().as_u64()
    ))
}

/// First release that reads `org.gradle.unsafe.isolated-projects`: Gradle 7.1 registers it as
/// `StartParameterBuildOptions.IsolatedProjectsOption` and refuses it beside an explicitly
/// disabled configuration cache; 7.0 has neither.
const GRADLE_UNSAFE_ISOLATED_PROJECTS: GradleRelease = GradleRelease::new(7, 1, 0);
/// First release that reads `org.gradle.isolated-projects`.
const GRADLE_CANONICAL_ISOLATED_PROJECTS: GradleRelease = GradleRelease::new(9, 7, 0);

#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
struct GradleRelease {
    major: u32,
    minor: u32,
    patch: u32,
}

impl GradleRelease {
    const fn new(major: u32, minor: u32, patch: u32) -> Self {
        Self {
            major,
            minor,
            patch,
        }
    }
}

/// An explicit `false` from either recognized name disables isolated projects.
fn record_isolated_projects(enabled: &mut Option<bool>, value: Option<bool>) {
    match value {
        Some(false) => *enabled = Some(false),
        Some(true) if *enabled != Some(false) => *enabled = Some(true),
        _ => {}
    }
}

/// The user Gradle home wins over the project file for this property name.
fn effective_property(user_home: Option<&Path>, project: &Path, key: &str) -> Option<bool> {
    if let Some(home) = user_home {
        if let Some(value) = property_assignment(&home.join("gradle.properties"), key) {
            return Some(value);
        }
    }
    property_assignment(&project.join("gradle.properties"), key)
}

/// Within one file the last assignment wins. A commented line is not a setting.
fn property_assignment(file: &Path, key: &str) -> Option<bool> {
    let text = std::fs::read_to_string(file).ok()?;
    let mut found = None;
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with('!') {
            continue;
        }
        let Some((name, value)) = line.split_once('=') else {
            continue;
        };
        if name.trim() == key {
            found = Some(value.trim().trim_matches('"').eq_ignore_ascii_case("true"));
        }
    }
    found
}

fn gradle_wrapper_release(project: &Path) -> Option<GradleRelease> {
    let text =
        std::fs::read_to_string(project.join("gradle/wrapper/gradle-wrapper.properties")).ok()?;
    release_from_wrapper(&text)
}

fn release_from_wrapper(text: &str) -> Option<GradleRelease> {
    for line in text.lines() {
        let line = line.trim();
        if line.is_empty() || line.starts_with('#') || line.starts_with('!') {
            continue;
        }
        let Some((key, value)) = line.split_once('=') else {
            continue;
        };
        if key.trim() == "distributionUrl" {
            return release_in_distribution_url(value.trim());
        }
    }
    None
}

fn release_in_distribution_url(url: &str) -> Option<GradleRelease> {
    let marker = "gradle-";
    let start = url.rfind(marker)? + marker.len();
    let mut parts = [0u32; 3];
    let mut index = 0usize;
    let mut number: Option<u32> = None;
    for byte in url[start..].bytes() {
        if byte.is_ascii_digit() {
            let slot = number.get_or_insert(0);
            *slot = slot
                .saturating_mul(10)
                .saturating_add(u32::from(byte - b'0'));
        } else if byte == b'.' && index < 2 {
            parts[index] = number.take()?;
            index += 1;
        } else {
            break;
        }
    }
    parts[index] = number?;
    Some(GradleRelease::new(parts[0], parts[1], parts[2]))
}

fn is_gradle_build_file(path: &Path) -> bool {
    let Some(name) = path.file_name().and_then(|name| name.to_str()) else {
        return false;
    };
    name.ends_with(".gradle")
        || name.ends_with(".gradle.kts")
        || name == "gradle.properties"
        || name == "libs.versions.toml"
        || name == "gradle-wrapper.properties"
        || name == "gradle.lockfile"
}

fn parse_model(root: &Path, stdout: &str) -> Result<ProjectModel, ProbeError> {
    let mut projects = Vec::new();
    for line in stdout.lines() {
        let Some(payload) = line.trim_start().strip_prefix(SENTINEL) else {
            continue;
        };
        let project: GradleProject = serde_json::from_str(payload)
            .map_err(|error| ProbeError::Parse(format!("{error} in `{payload}`")))?;
        projects.push(project);
    }
    if projects.is_empty() {
        return Err(ProbeError::Parse(
            "no project model lines in gradle output".to_string(),
        ));
    }

    let jdk_home = projects
        .iter()
        .find_map(|project| project.java_home.clone())
        .map(PathBuf::from);
    let mut modules = Vec::new();
    for project in &projects {
        // Android and multiplatform replace the plain source-set view: an Android project's JVM
        // sources are organised per variant, and a multiplatform project has no SourceSetContainer
        // at all. Prefer the richer view when the corresponding plugin reported one.
        if !project.android_variants.is_empty() {
            for variant in &project.android_variants {
                modules.push(android_module_of(project, variant));
            }
        } else if !project.kotlin_compilations.is_empty() {
            for compilation in project
                .kotlin_compilations
                .iter()
                .filter(|compilation| compilation.platform == "jvm")
            {
                modules.push(kmp_module_of(project, compilation));
            }
        } else {
            for source_set in &project.source_sets {
                modules.push(module_of(project, source_set));
            }
        }
    }
    link_project_dependencies(&mut modules);
    let classpaths = modules
        .iter()
        .map(|module| super::intellij_classpath::realize_direct(&module.classpath, &modules))
        .collect::<Vec<_>>();
    for (module, classpath) in modules.iter_mut().zip(classpaths) {
        module.classpath = classpath;
    }
    Ok(ProjectModel {
        root: root.to_path_buf(),
        kind: ProviderKind::Gradle,
        jdk_home,
        modules,
        repository_libraries: Vec::new(),
    })
}

/// A project dependency is that project's production module. A plain JVM project calls it `main`.
/// A Kotlin Multiplatform project calls the JVM one `jvm/main`, so linking every edge to `main`
/// points at a module that was never created.
fn link_project_dependencies(modules: &mut [Module]) {
    let present = modules
        .iter()
        .filter_map(|module| module.id.as_ref().map(|id| id.as_str().to_string()))
        .collect::<std::collections::HashSet<_>>();
    for module in modules.iter_mut() {
        let mut linked = Vec::new();
        for dependency in &module.depends_on {
            let id = production_dependency(dependency.as_str(), &present);
            if !linked.iter().any(|existing: &ModuleId| existing == &id) {
                linked.push(id);
            }
        }
        let test_module = module
            .source_roots
            .iter()
            .any(|root| root.kind == SourceRootKind::Test);
        if test_module {
            if let Some(project) = module
                .id
                .as_ref()
                .and_then(|id| id.as_str().rsplit_once(':'))
                .map(|(project, _)| project)
            {
                let production = production_module_id(project, &present);
                if present.contains(production.as_str())
                    && module.id.as_ref() != Some(&production)
                    && !linked.iter().any(|existing| existing == &production)
                {
                    linked.push(production);
                }
            }
        }
        module.depends_on = linked;
    }
}

fn production_dependency(
    dependency: &str,
    present: &std::collections::HashSet<String>,
) -> ModuleId {
    match dependency.rsplit_once(':') {
        Some((project, "main")) => production_module_id(project, present),
        _ => ModuleId::raw(dependency),
    }
}

fn production_module_id(project: &str, present: &std::collections::HashSet<String>) -> ModuleId {
    let main = ModuleId::new(project, "main");
    if present.contains(main.as_str()) {
        return main;
    }
    let jvm_main = ModuleId::new(project, "jvm/main");
    if present.contains(jvm_main.as_str()) {
        return jvm_main;
    }
    main
}

fn module_of(project: &GradleProject, source_set: &GradleSourceSet) -> Module {
    let kind = if is_test_source_set(&source_set.name) {
        SourceRootKind::Test
    } else {
        SourceRootKind::Source
    };
    let mut module = Module::new(
        ModuleId::new(&project.path, &source_set.name),
        &project.project_dir,
    );
    module.display_name = format!("{}:{}", project.name, source_set.name);
    module.source_roots = source_set
        .roots
        .iter()
        .map(|root| SourceRoot {
            path: PathBuf::from(root),
            kind,
            generated: false,
            package_prefix: String::new(),
        })
        .collect();
    module.classpath = source_set.classpath.iter().map(PathBuf::from).collect();
    module.outputs = source_set
        .output
        .iter()
        .map(ModuleOutput::classes)
        .collect();
    module.archive = source_set.archive.as_deref().map(PathBuf::from);
    module.jvm_target = project.jvm_target.clone();
    module.kotlinc_args = merged_kotlinc_args(&project.kotlinc_args, &source_set.kotlinc_args);
    // The source set's own project dependencies are exact; the project-level list only knows
    // `implementation`/`api` and stands in for a probe that recorded nothing per source set.
    let project_deps = source_set
        .project_deps
        .as_ref()
        .unwrap_or(&project.project_deps);
    module.depends_on = project_deps
        .iter()
        .map(|path| ModuleId::new(path, "main"))
        .collect();

    // A test source set sees its own project's `main` output, including `internal` declarations:
    // that is Gradle's association, and the compiler needs it as a friend path.
    if kind == SourceRootKind::Test {
        let main = ModuleId::new(&project.path, "main");
        if !module.depends_on.contains(&main) {
            module.depends_on.push(main);
        }
        for output in project
            .source_sets
            .iter()
            .filter(|set| set.name == "main")
            .flat_map(|set| set.output.iter())
        {
            module.friend_paths.push(PathBuf::from(output));
        }
    }
    module
}

/// One Kotlin Multiplatform compilation becomes a module keyed `<target>/<compilation>`
/// (e.g. `jvm/main`), so `jvm/main` and `jvm/test` stay distinct compilation units.
fn kmp_module_of(project: &GradleProject, compilation: &KotlinCompilation) -> Module {
    let source_set = format!("{}/{}", compilation.target, compilation.name);
    let kind = if compilation.is_test {
        SourceRootKind::Test
    } else {
        SourceRootKind::Source
    };
    let mut module = Module::new(
        ModuleId::new(&project.path, &source_set),
        &project.project_dir,
    );
    module.display_name = format!("{}:{source_set}", project.name);
    module.source_roots = compilation
        .roots
        .iter()
        .map(|root| SourceRoot {
            path: PathBuf::from(root),
            kind,
            generated: false,
            package_prefix: String::new(),
        })
        .collect();
    module.classpath = compilation.classpath.iter().map(PathBuf::from).collect();
    module.outputs = compilation
        .output
        .iter()
        .map(ModuleOutput::classes)
        .collect();
    module.archive = compilation.archive.as_deref().map(PathBuf::from);
    module.friend_paths = compilation.associates.iter().map(PathBuf::from).collect();
    module.jvm_target = compilation
        .jvm_target
        .clone()
        .or_else(|| project.jvm_target.clone());
    module.kotlinc_args = merged_kotlinc_args(&project.kotlinc_args, &compilation.kotlinc_args);
    module.depends_on = project
        .project_deps
        .iter()
        .map(|path| ModuleId::new(path, "main"))
        .collect();
    module
}

/// One Android variant becomes a module keyed by the variant name (`debug`, `release`). The AGP
/// compile classpath already includes the platform `android.jar` and the generated `R.jar`.
fn android_module_of(project: &GradleProject, variant: &AndroidVariant) -> Module {
    let kind = if variant.is_test {
        SourceRootKind::Test
    } else {
        SourceRootKind::Source
    };
    let mut module = Module::new(
        ModuleId::new(&project.path, &variant.name),
        &project.project_dir,
    );
    module.display_name = format!("{}:{}", project.name, variant.name);
    module.source_roots = variant
        .roots
        .iter()
        .map(|root| SourceRoot {
            path: PathBuf::from(root),
            kind,
            generated: false,
            package_prefix: String::new(),
        })
        .collect();
    module.classpath = variant.classpath.iter().map(PathBuf::from).collect();
    module.outputs = variant.output.iter().map(ModuleOutput::classes).collect();
    module.jvm_target = project.jvm_target.clone();
    module.kotlinc_args = merged_kotlinc_args(&project.kotlinc_args, &variant.kotlinc_args);
    module.depends_on = project
        .project_deps
        .iter()
        .map(|path| ModuleId::new(path, "main"))
        .collect();
    module
}

fn merged_kotlinc_args(project: &[String], compilation: &[String]) -> Vec<String> {
    let mut merged = Vec::new();
    for argument in project.iter().chain(compilation) {
        if !merged.contains(argument) {
            merged.push(argument.clone());
        }
    }
    merged
}

fn is_test_source_set(name: &str) -> bool {
    name == "test" || name.ends_with("Test") || name.ends_with("test")
}

fn gradle_failure_summary(stderr: &str, stdout: &str) -> String {
    gradle_failure_details(stderr)
        .or_else(|| gradle_failure_details(stdout))
        .unwrap_or_else(|| {
            stderr
                .lines()
                .chain(stdout.lines())
                .map(str::trim)
                .find(|line| !line.is_empty())
                .unwrap_or_default()
                .to_string()
        })
}

fn gradle_failure_details(output: &str) -> Option<String> {
    let mut lines = output.lines().map(str::trim_end);
    while let Some(line) = lines.next() {
        if line.trim() != "* What went wrong:" {
            continue;
        }
        let mut cause = Vec::new();
        let mut truncated = false;
        for detail in lines.by_ref() {
            let detail = detail.trim();
            if detail.is_empty() || detail.starts_with('*') {
                break;
            }
            let detail = detail.trim_start_matches('>').trim();
            if detail.is_empty() {
                continue;
            }
            if cause.len() == MAX_FAILURE_DETAILS {
                truncated = true;
                break;
            }
            cause.push(detail);
        }
        if !cause.is_empty() {
            let mut summary = cause.join(" — ");
            if truncated {
                summary.push_str(" — ...");
            }
            return Some(summary);
        }
    }
    None
}

