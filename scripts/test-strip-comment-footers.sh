#!/usr/bin/env bash
# Contract of scripts/strip-comment-footers.sh against a stand-in `gh`: a comment, review comment or
# review that ends with an integration's footer is written back without it, by the method its kind
# takes; a clean comment and Dependabot's text are not written at all.
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
failed=0
fail() { echo "FAIL: $*" >&2; failed=$((failed + 1)); }

footer=$'\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_'

# The stand-in serves $work/api/<path>.json for a read and $work/api/<path>.list for a listing,
# and records every write as "<method> <path>" in $work/writes with its body in $work/body/<path>.
mkdir -p "$work/bin" "$work/api" "$work/body"
cat > "$work/bin/gh" <<'GH'
#!/usr/bin/env bash
set -euo pipefail
[[ $1 == api ]] && shift
method=GET paginate=0 jq_filter= field=
while (($#)); do
  case $1 in
    -X) method=$2; shift 2 ;;
    -F) field=$2; shift 2 ;;
    --paginate) paginate=1; shift ;;
    --jq) jq_filter=$2; shift 2 ;;
    *) path=$1; shift ;;
  esac
done
if [[ $method == GET ]]; then
  if ((paginate)); then
    jq -r "$jq_filter" "$GH_FAKE/api/${path%%\?*}.list"
  else
    cat "$GH_FAKE/api/$path.json"
  fi
else
  echo "$method $path" >> "$GH_FAKE/writes"
  mkdir -p "$(dirname "$GH_FAKE/body/$path")"
  cp "${field#body=@}" "$GH_FAKE/body/$path"
fi
GH
chmod +x "$work/bin/gh"

# <path> <login> <body>
item() {
  mkdir -p "$(dirname "$work/api/$1")"
  jq -n --arg url "https://api.github.com/$1" --arg login "$2" --arg body "$3" \
    '{url: $url, user: {login: $login}, body: $body}' > "$work/api/$1.json"
}

run() {
  rm -f "$work/writes"
  : > "$work/writes"
  PATH="$work/bin:$PATH" GH_FAKE=$work GH_REPO=o/r \
    "$repo/scripts/strip-comment-footers.sh" "$@" > /dev/null
}

# <name> <expected writes>
writes() {
  local got
  got=$(cat "$work/writes")
  [[ $got == "$2" ]] || fail "$1: wrote $(printf '%q' "$got"), expected $(printf '%q' "$2")"
}

# <name> <path> <expected body>
body() {
  local got
  got=$(cat "$work/body/$2"; printf x)
  got=${got%x}
  [[ $got == "$3" ]] || fail "$1: body $(printf '%q' "$got"), expected $(printf '%q' "$3")"
}

item repos/o/r/issues/comments/1 qnox "Fixed in abc.$footer"
run --comment repos/o/r/issues/comments/1
writes "issue comment" "PATCH repos/o/r/issues/comments/1"
body "issue comment" repos/o/r/issues/comments/1 $'Fixed in abc.\n'

item repos/o/r/pulls/comments/2 qnox "Done.$footer"
run --comment https://api.github.com/repos/o/r/pulls/comments/2
writes "review comment by URL" "PATCH repos/o/r/pulls/comments/2"
body "review comment by URL" repos/o/r/pulls/comments/2 $'Done.\n'

item repos/o/r/pulls/7/reviews/3 qnox "Looks right.$footer"
run --comment repos/o/r/pulls/7/reviews/3
writes "review" "PUT repos/o/r/pulls/7/reviews/3"
body "review" repos/o/r/pulls/7/reviews/3 $'Looks right.\n'

item repos/o/r/issues/comments/4 qnox $'No footer here.\n\n---\nNotes.'
run --comment repos/o/r/issues/comments/4
writes "clean comment" ""

item repos/o/r/issues/comments/5 'dependabot[bot]' "Release notes.$footer"
run --comment repos/o/r/issues/comments/5
writes "dependabot" ""

# A sweep reads both repository-wide listings and writes only what carries a footer.
jq -s . "$work/api/repos/o/r/issues/comments/1.json" "$work/api/repos/o/r/issues/comments/4.json" \
  "$work/api/repos/o/r/issues/comments/5.json" > "$work/api/repos/o/r/issues/comments.list"
jq -s . "$work/api/repos/o/r/pulls/comments/2.json" > "$work/api/repos/o/r/pulls/comments.list"
run --since 2026-01-01T00:00:00Z
writes "sweep" $'PATCH repos/o/r/issues/comments/1\nPATCH repos/o/r/pulls/comments/2'
body "sweep" repos/o/r/pulls/comments/2 $'Done.\n'

[ "$failed" -eq 0 ] || { echo "strip-comment-footers: $failed failed assertions" >&2; exit 1; }
echo "strip-comment-footers: ok"
