#!/usr/bin/env bash
# Contract of scripts/check-attribution.sh --strip-footer: the footers integrations append to PR
# text are removed in every spacing and line ending, and nothing else in the text changes.
set -euo pipefail

repo=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
failed=0
fail() { echo "FAIL: $*" >&2; failed=$((failed + 1)); }

footer='_Generated by [Claude Code](https://claude.ai/code)_'

# <name> <input> <expected output>
strips() {
  printf '%s' "$2" > "$work/in"
  local got
  got=$("$repo/scripts/check-attribution.sh" --strip-footer "$work/in"; printf x)
  got=${got%x}
  [[ $got == "$3" ]] || fail "$1: got $(printf '%q' "$got"), expected $(printf '%q' "$3")"
}

strips "appended footer" $'Summary.\n\n---\n'"$footer" $'Summary.\n'
strips "trailing newline" $'Summary.\n\n---\n'"$footer"$'\n' $'Summary.\n'
strips "CRLF" $'Summary.\r\n\r\n---\r\n'"$footer"$'\r\n' $'Summary.\r\n'
strips "spaces and extra blank lines" $'Summary.\n \n\n  ---  \n\n  '"$footer"$'  \n' $'Summary.\n'
strips "without the rule" $'Summary.\n\n'"$footer" $'Summary.\n'
strips "twice" $'Summary.\n\n---\n'"$footer"$'\n\n---\n'"$footer" $'Summary.\n'
strips "mid-body" $'Summary.\n\n---\n'"$footer"$'\nMore.\n' $'Summary.\nMore.\n'
strips "only the footer" $'---\n'"$footer" ''
strips "no footer" $'Summary.\n\n---\nNotes.\n' $'Summary.\n\n---\nNotes.\n'
strips "footer words inside a line" $'See '"$footer"$' here.\n' $'See '"$footer"$' here.\n'

cursor_div='<div><a href="https://cursor.com/agents/bc-1?cursor_ref=pr_footer&cursor_cta=open_in_web"><picture><source media="(prefers-color-scheme: dark)" srcset="https://cursor.com/assets/images/open-in-web-dark.png"><img alt="Open in Web" width="114" height="28" src="https://cursor.com/assets/images/open-in-web-dark.png"></picture></a>&nbsp;<a href="https://cursor.com/background-agent?bcId=bc-1&cursor_ref=pr_footer&cursor_cta=open_in_cursor"><picture><img alt="Open in Cursor" width="131" height="28" src="https://cursor.com/assets/images/open-in-cursor-dark.png"></picture></a>&nbsp;</div>'
strips "cursor markers and links" \
  $'<!-- CURSOR_AGENT_PR_BODY_BEGIN -->\nSummary.\n\nDetails.\n<!-- CURSOR_AGENT_PR_BODY_END -->\n\n'"$cursor_div" \
  $'Summary.\n\nDetails.\n'
strips "cursor CRLF" \
  $'<!-- CURSOR_AGENT_PR_BODY_BEGIN -->\r\nSummary.\r\n<!-- CURSOR_AGENT_PR_BODY_END -->\r\n\r\n'"$cursor_div"$'\r\n' \
  $'Summary.\r\n'
strips "cursor and the rule footer" \
  $'<!-- CURSOR_AGENT_PR_BODY_BEGIN -->\nSummary.\n<!-- CURSOR_AGENT_PR_BODY_END -->\n\n'"$cursor_div"$'\n\n---\n'"$footer" \
  $'Summary.\n'
strips "other div kept" $'Summary.\n\n<div><a href="https://example.com/">x</a></div>\n' $'Summary.\n\n<div><a href="https://example.com/">x</a></div>\n'

robot='🤖 Generated with [Claude Code](https://claude.com/claude-code)'
session='https://claude.ai/code/session_01AbC'
strips "robot footer and session link" $'Summary.\n\n'"$robot"$'\n\n'"$session"$'\n' $'Summary.\n'
strips "robot footer without session link" $'Summary.\n\n---\n'"$robot" $'Summary.\n'
strips "robot footer CRLF" $'Summary.\r\n\r\n'"$robot"$'\r\n\r\n'"$session"$'\r\n' $'Summary.\r\n'
strips "other session link kept" $'Summary.\n\n'"$session"$'\n' $'Summary.\n\n'"$session"$'\n'

header='<!-- claude-projects-attribution: {"github_login":"someone"} -->'
requested='_Requested by **Someone** · [project thread](https://claude.ai/code/project/chan_1?thread=cmsg_2)_'
strips "header and requested-by" "$header"$'\n'"$requested"$'\n\n## What\n\nSummary.\n' $'## What\n\nSummary.\n'
strips "header CRLF" "$header"$'\r\n'"$requested"$'\r\n\r\nSummary.\r\n' $'Summary.\r\n'
strips "requested-by of another link" \
  $'_Requested by **Someone** · [session](https://claude.ai/code/session_3)_\nSummary.\n' $'Summary.\n'
strips "header, requested-by and footer" \
  "$header"$'\n'"$requested"$'\n\nSummary.\n\n---\n'"$footer"$'\n' $'Summary.\n'
strips "requested-by elsewhere kept" \
  $'_Requested by **Someone** · [issue](https://example.com/1)_\n' $'_Requested by **Someone** · [issue](https://example.com/1)_\n'

# What is left still goes through --text: a stripped footer passes, any other mention still fails.
printf 'Title\n\nSummary.\n\n---\n%s' "$footer" > "$work/pr"
"$repo/scripts/check-attribution.sh" --strip-footer "$work/pr" > "$work/clean"
"$repo/scripts/check-attribution.sh" --text "$work/clean" "pull request text" 2>/dev/null \
  || fail "the stripped text was refused"
printf 'Title\n\nWritten with Claude.\n\n---\n%s' "$footer" > "$work/pr"
"$repo/scripts/check-attribution.sh" --strip-footer "$work/pr" > "$work/clean"
! "$repo/scripts/check-attribution.sh" --text "$work/clean" "pull request text" 2>/dev/null \
  || fail "a mention outside the footer was accepted"

[ "$failed" -eq 0 ] || { echo "check-attribution: $failed failed assertions" >&2; exit 1; }
echo "check-attribution: ok"
