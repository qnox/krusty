#!/usr/bin/env bash
# Enforce the authorship rule in AGENTS.md: no AI, assistant or tool attribution in commit
# identities, commit messages, or pull request text.
#
#   scripts/check-attribution.sh <rev-range>        check every commit in the range (CI)
#   scripts/check-attribution.sh --message <file>   check a commit message and the identity the
#                                                   commit is about to get (commit-msg hook)
#   scripts/check-attribution.sh --text <file>      check free text such as a PR title and body
#   scripts/check-attribution.sh --strip-footer <file>
#                                                   print the file without the footer an integration
#                                                   appends to the PR text it posts
set -euo pipefail

# Assistant and vendor names, their no-reply addresses, and the usual attribution phrases.
pattern='claude|codex|anthropic|openai|copilot|chatgpt|gemini|cursor(agent| agent)|\bgpt-?[0-9]|generated (with|by)|🤖'

failures=0

report() {
  echo "attribution: $1" >&2
  failures=$((failures + 1))
}

check_text() {
  local what=$1 text=$2 hits
  hits=$(grep -inE "$pattern" <<<"$text" || true)
  [[ -z $hits ]] || report "$what mentions an AI tool:"$'\n'"$(sed 's/^/    /' <<<"$hits")"
}

case "${1:-}" in
  --message)
    check_text "commit message" "$(grep -v '^#' "$2")"
    check_text "author" "$(git var GIT_AUTHOR_IDENT)"
    check_text "committer" "$(git var GIT_COMMITTER_IDENT)"
    ;;
  --text)
    check_text "${3:-text}" "$(cat "$2")"
    ;;
  --strip-footer)
    # Each footer goes with the blank lines before it, in any spacing or line ending. Only footers
    # go; any other mention stays and still fails --text.
    #  - a `---` rule (optional) and the `_Generated by [Claude Code](…)_` line;
    #  - the same line in its `🤖 Generated with [Claude Code](…)` form, with the session link
    #    line under it;
    #  - Cursor's `<!-- CURSOR_AGENT_PR_BODY_BEGIN/END -->` markers (the text between them stays)
    #    and its `<div>` of "Open in" links to cursor.com.
    # A header goes with the blank lines after it:
    #  - the `<!-- claude-projects-attribution: … -->` comment;
    #  - the `_Requested by **…** · [project thread](https://claude.ai/code/…)_` line.
    perl -CSD -0777 -pe '
      s/^(?:[ \t]*\r?\n)*(?:[ \t]*-{3,}[ \t]*\r?\n(?:[ \t]*\r?\n)*)?[ \t]*_Generated (?:by|with) \[Claude Code\]\([^)\s]*\)_[ \t]*(?=\r?\n|\z)(?:\r?\n)?//gim;
      s/^(?:[ \t]*\r?\n)*(?:[ \t]*-{3,}[ \t]*\r?\n(?:[ \t]*\r?\n)*)?[ \t]*\x{1F916}[ \t]*Generated (?:by|with) \[Claude Code\]\([^)\s]*\)[ \t]*(?:\r?\n(?:[ \t]*\r?\n)*[ \t]*https:\/\/claude\.ai\/code\/session_[^\s]*[ \t]*)?(?=\r?\n|\z)(?:\r?\n)?//gim;
      s/^[ \t]*<!--[ \t]*claude-projects-attribution:[^\n]*?-->[ \t]*(?:\r?\n(?:[ \t]*\r?\n)*|\z)//gm;
      s/^[ \t]*_Requested by [^\n]*?\[[^\]\n]*\]\(https:\/\/claude\.ai\/code\/[^)\s]*\)_[ \t]*(?:\r?\n(?:[ \t]*\r?\n)*|\z)//gm;
      s/^[ \t]*<!--[ \t]*CURSOR_AGENT_PR_BODY_(?:BEGIN|END)[ \t]*-->[ \t]*(?:\r?\n|\z)//gm;
      s/^(?:[ \t]*\r?\n)*[ \t]*<div>[ \t]*<a href="https:\/\/cursor\.com\/[^"]*cursor_ref=pr_footer[^"]*">.*?<\/div>[ \t]*(?:\r?\n|\z)//gms;
    ' "$2"
    exit 0
    ;;
  "" | -*)
    sed -n '2,11p' "$0" >&2
    exit 2
    ;;
  *)
    while read -r sha; do
      # Dependabot is a dependency bot, not an assistant; its messages quote upstream text.
      [[ $(git log -1 --format=%ae "$sha") == *'+dependabot[bot]@users.noreply.github.com' ]] && continue
      check_text "commit $sha identity" "$(git log -1 --format='%an <%ae> / %cn <%ce>' "$sha")"
      check_text "commit $sha message" "$(git log -1 --format='%B' "$sha")"
    done < <(git rev-list "$1")
    ;;
esac

if ((failures)); then
  echo "attribution: see \"Authorship and attribution\" in AGENTS.md" >&2
  exit 1
fi
